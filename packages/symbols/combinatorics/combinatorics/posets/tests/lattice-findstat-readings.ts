// Independent readings of the lattice statistics adopted from FindStat, written against FindStat's definitions rather than
// against the expressions: the lattice as a boolean matrix, joins and meets found by brute force from the order, subsets and
// chains searched exhaustively.

import { type Poset, posetsOfSize, strictOrder } from "./poset-findstat-readings.ts";

const range = (from: number, to: number): number[] =>
  Array.from({ length: Math.max(0, to - from + 1) }, (_, k) => from + k);
const sum = (values: readonly number[]): number => values.reduce((a, b) => a + b, 0);
const largest = (values: readonly number[]): number => values.reduce((a, b) => Math.max(a, b), -Infinity);

/** A finite lattice on the listed elements, the order a boolean matrix; every operation is a search. */
class Lattice {
  constructor(
    readonly elements: readonly number[],
    /** x ≤ y. */
    readonly le: (x: number, y: number) => boolean,
  ) {}

  /** The least of the common upper bounds of `set` (the bottom for the empty set), or undefined. */
  joinOf(set: readonly number[]): number | undefined {
    const upper = this.elements.filter((u) => set.every((s) => this.le(s, u)));
    return upper.find((u) => upper.every((v) => this.le(u, v)));
  }
  /** The greatest of the common lower bounds of `set` (the top for the empty set), or undefined. */
  meetOf(set: readonly number[]): number | undefined {
    const lower = this.elements.filter((l) => set.every((s) => this.le(l, s)));
    return lower.find((l) => lower.every((v) => this.le(v, l)));
  }
  private readonly joins = new Map<number, number>();
  private readonly meets = new Map<number, number>();
  /** The pair's join, found once by search. */
  join = (x: number, y: number): number => {
    const key = x * 1000 + y;
    if (!this.joins.has(key)) this.joins.set(key, this.joinOf([x, y])!);
    return this.joins.get(key)!;
  };
  meet = (x: number, y: number): number => {
    const key = x * 1000 + y;
    if (!this.meets.has(key)) this.meets.set(key, this.meetOf([x, y])!);
    return this.meets.get(key)!;
  };
  private readonly neutral = new Map<number, boolean>();
  get bottom(): number {
    return this.joinOf([])!;
  }
  get top(): number {
    return this.meetOf([])!;
  }
  lt = (x: number, y: number): boolean => x !== y && this.le(x, y);
  covers = (y: number, x: number): boolean =>
    this.lt(x, y) && !this.elements.some((z) => this.lt(x, z) && this.lt(z, y));
  lowerCovers = (y: number): number[] => this.elements.filter((x) => this.covers(y, x));
  upperCovers = (x: number): number[] => this.elements.filter((y) => this.covers(y, x));
  isJoinIrreducible = (x: number): boolean => this.lowerCovers(x).length === 1;
  /** The elements of the interval [x, y] as a lattice. */
  interval(x: number, y: number): Lattice {
    return new Lattice(
      this.elements.filter((z) => this.le(x, z) && this.le(z, y)),
      this.le,
    );
  }
  /** Every subset of the elements. */
  subsets(): number[][] {
    return Array.from({ length: 2 ** this.elements.length }, (_, mask) =>
      this.elements.filter((_, k) => (mask >> k) & 1),
    );
  }
  hasComplement = (x: number): boolean =>
    this.elements.some((y) => this.meet(x, y) === this.bottom && this.join(x, y) === this.top);
  /** The sublattice generated by `seed`: closed under join and meet. */
  generated(seed: readonly number[]): number[] {
    let found = [...new Set(seed)];
    for (let size = 0; size !== found.length;) {
      size = found.length;
      const snapshot = found;
      found = [
        ...new Set([
          ...snapshot,
          ...snapshot.flatMap((a) => snapshot.flatMap((b) => [this.join(a, b), this.meet(a, b)])),
        ]),
      ];
    }
    return found;
  }
  isDistributive(set: readonly number[]): boolean {
    return set.every((a) =>
      set.every((b) => set.every((c) => this.meet(a, this.join(b, c)) === this.join(this.meet(a, b), this.meet(a, c)))),
    );
  }
  /** Neutral: e generates a distributive sublattice with every p and q. */
  isNeutral = (e: number): boolean => {
    if (!this.neutral.has(e))
      this.neutral.set(
        e,
        this.elements.every((p) => this.elements.every((q) => this.isDistributive(this.generated([e, p, q])))),
      );
    return this.neutral.get(e)!;
  };
  center(): number[] {
    return this.elements.filter((e) => this.isNeutral(e) && this.hasComplement(e));
  }
}

/** The lattice a poset's lower covers give, elements from 0. */
const latticeOf = (covers: Poset): Lattice => {
  const less = strictOrder(covers);
  return new Lattice(range(0, covers.length - 1), (x, y) => x === y || less[x]![y]!);
};

/** Whether every pair has a join and a meet, by search; the poset with no elements is a lattice. */
export const isLatticeReading = (covers: Poset): boolean => {
  const l = latticeOf(covers);
  return l.elements.every((x) =>
    l.elements.every((y) => l.joinOf([x, y]) !== undefined && l.meetOf([x, y]) !== undefined),
  );
};

/** Every naturally labeled lattice on n elements. */
export const latticesOfSize = (n: number): Poset[] => posetsOfSize(n).filter(isLatticeReading);

/** μ(bottom, top) by its recurrence. */
const moebiusInvariant = (l: Lattice): number => {
  const mu = new Map<number, number>();
  for (const y of l.elements.toSorted((a, b) => (l.lt(a, b) ? -1 : l.lt(b, a) ? 1 : 0))) {
    mu.set(y, y === l.bottom ? 1 : 0 - sum(l.elements.filter((z) => l.lt(z, y)).map((z) => mu.get(z)!)));
  }
  return mu.get(l.top)!;
};

/** The factors a lattice splits into: split at a central element other than the ends, and count the pieces. */
const directFactors = (l: Lattice): number => {
  const c = l.center().find((e) => e !== l.bottom && e !== l.top);
  return c === undefined ? 1 : directFactors(l.interval(l.bottom, c)) + directFactors(l.interval(c, l.top));
};

/** Whether `step` from e to j is allowed: j is the join of the upper covers of e below it. */
const isSmallStep = (l: Lattice, e: number, j: number): boolean => {
  const covers = l.upperCovers(e).filter((c) => l.le(c, j));
  return covers.length > 0 && l.joinOf(covers) === j;
};
/** The small-interval chains from the bottom to the top, as lists of elements. */
const smallChains = (l: Lattice, from: number = l.bottom): number[][] =>
  from === l.top
    ? [[from]]
    : l.elements
        .filter((j) => l.lt(from, j) && isSmallStep(l, from, j))
        .flatMap((j) => smallChains(l, j).map((c) => [from, ...c]));

/** The longest chain's element count. */
const longestChain = (l: Lattice, from: number = l.bottom): number =>
  1 + Math.max(0, ...l.elements.filter((y) => l.lt(from, y)).map((y) => longestChain(l, y)));

const isLinear = (l: Lattice): boolean => l.elements.every((a) => l.elements.every((b) => l.le(a, b) || l.le(b, a)));

/** The fewest elements of a small-interval chain from the bottom to the top, found by search. */
export const fewestSmallChainElements = (covers: Poset): number =>
  Math.min(...smallChains(latticeOf(covers)).map((c) => c.length));

export const LATTICE_READINGS: Readonly<Record<string, (covers: Poset) => number | undefined>> = {
  ModularElementCount: (p) => {
    const l = latticeOf(p);
    return l.elements.filter((a) =>
      l.elements.every((y) =>
        l.elements.filter((z) => l.le(z, a)).every((z) => l.meet(a, l.join(y, z)) === l.join(l.meet(a, y), z)),
      ),
    ).length;
  },
  LeftModularElementCount: (p) => {
    const l = latticeOf(p);
    return l.elements.filter((a) =>
      l.elements.every((y) =>
        l.elements.filter((z) => l.le(y, z)).every((z) => l.meet(l.join(y, a), z) === l.join(y, l.meet(a, z))),
      ),
    ).length;
  },
  LatticeCenterRank: (p) => Math.log2(latticeOf(p).center().length),
  JoinPrimeCount: (p) => {
    const l = latticeOf(p);
    return l.elements.filter(
      (a) =>
        a !== l.bottom &&
        l.elements.every((x) => l.elements.every((y) => !l.le(a, l.join(x, y)) || l.le(a, x) || l.le(a, y))),
    ).length;
  },
  NeutralElementCount: (p) => {
    const l = latticeOf(p);
    return l.elements.filter(l.isNeutral).length;
  },
  AtomCount: (p) => {
    const l = latticeOf(p);
    return l.elements.filter((a) => l.covers(a, l.bottom)).length;
  },
  JoinIrreducibleCount: (p) => latticeOf(p).elements.filter(latticeOf(p).isJoinIrreducible).length,
  DoublyIrreducibleCount: (p) => {
    const l = latticeOf(p);
    return l.elements.filter((x) => l.lowerCovers(x).length === 1 && l.upperCovers(x).length === 1).length;
  },
  MoebiusInvariant: (p) => moebiusInvariant(latticeOf(p)),
  FranklNumber: (p) => {
    const l = latticeOf(p);
    const irreducible = l.elements.filter(l.isJoinIrreducible);
    return irreducible.length === 0
      ? undefined
      : largest(irreducible.map((x) => l.elements.length - 2 * l.elements.filter((y) => l.le(x, y)).length));
  },
  ShortestSmallIntervalChainCount: (p) => {
    const chains = smallChains(latticeOf(p));
    const fewest = Math.min(...chains.map((c) => c.length));
    return chains.filter((c) => c.length === fewest).length;
  },
  // The chain that jumps from each element to the join of all its upper covers, the elements counted.
  CoverJoinChainSize: (p) => {
    const l = latticeOf(p);
    let size = 1;
    for (let e = l.bottom; e !== l.top; e = l.joinOf(l.upperCovers(e))!) size++;
    return size;
  },
  PopStackImageSize: (p) => {
    const l = latticeOf(p);
    return new Set(l.elements.map((x) => l.meet(x, l.meetOf(l.lowerCovers(x))!))).size;
  },
  LinearIntervalCount: (p) => {
    const l = latticeOf(p);
    return l.elements.flatMap((x) => l.elements.filter((y) => l.le(x, y) && isLinear(l.interval(x, y)))).length;
  },
  JoinIrreducibleCountMinusRank: (p) => {
    const l = latticeOf(p);
    return l.elements.filter(l.isJoinIrreducible).length - (longestChain(l) - 1);
  },
  UncomplementedElementCount: (p) => {
    const l = latticeOf(p);
    return l.elements.filter((x) => !l.hasComplement(x)).length;
  },
  DirectFactorCount: (p) => directFactors(latticeOf(p)),
  ZeroDivisorCount: (p) => {
    const l = latticeOf(p);
    return l.elements.filter(
      (a) => a !== l.bottom && l.elements.some((b) => b !== l.bottom && l.meet(a, b) === l.bottom),
    ).length;
  },
  SublatticeCount: (p) => {
    const l = latticeOf(p);
    return l
      .subsets()
      .filter((s) => s.every((a) => s.every((b) => s.includes(l.join(a, b)) && s.includes(l.meet(a, b))))).length;
  },
  // Join-irredundant subsets of the join-irreducible elements (a lattice's breadth is the same over all of them); at least 1.
  LatticeBreadth: (p) => {
    const l = latticeOf(p);
    const irreducible = new Lattice(l.elements.filter(l.isJoinIrreducible), l.le);
    const irredundant = (s: number[]): boolean => s.every((x) => l.joinOf(s.filter((y) => y !== x)) !== l.joinOf(s));
    return Math.max(
      1,
      ...irreducible
        .subsets()
        .filter(irredundant)
        .map((s) => s.length),
    );
  },
  NondegenerateBottomMeetSubsetCount: (p) => {
    const l = latticeOf(p);
    return l
      .subsets()
      .filter((s) => s.length > 0 && !s.includes(l.bottom) && !s.includes(l.top) && l.meetOf(s) === l.bottom).length;
  },
  BottomMeetSubsetCount: (p) => {
    const l = latticeOf(p);
    return l.subsets().filter((s) => s.length > 0 && l.meetOf(s) === l.bottom).length;
  },
  MinimalBottomMeetSubsetCount: (p) => {
    const l = latticeOf(p);
    const atBottom = l.subsets().filter((s) => s.length > 0 && l.meetOf(s) === l.bottom);
    return atBottom.filter((s) => !atBottom.some((t) => t.length < s.length && t.every((x) => s.includes(x)))).length;
  },
};
