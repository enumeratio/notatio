// Fetch the names Wolfram documents, and rewrite `src/wolfram-documented-data.ts`.
//
// `System`` holds symbols that have no reference page (`ArrowBox`, `CheckboxBox`: front-end
// boxes), so "Wolfram has the name" does not mean "reference.wolfram.com/language/ref/<name>
// answers". The documentation's alphabetical listing links every symbol page, and that is
// what the crosswalk consults before it writes a Wolfram link. The listing leaves out some
// pages that exist (`TestResultObject`), so a `System`` name it lacks is asked for directly. Rerun when the baseline
// kernel version moves:
//
//   node packages/reference/scripts/fetch-wolfram-documented.ts

import { writeFileSync } from "node:fs";
import { SYSTEM_NAMES } from "../../wolfram/src/system-names.ts";

const LISTING = "https://reference.wolfram.com/language/guide/AlphabeticalListing.html";

const response = await fetch(LISTING, { signal: AbortSignal.timeout(120_000) });
if (!response.ok) throw new Error(`${LISTING}: ${response.status}`);
const html = await response.text();

const listed = new Set([...html.matchAll(/\/ref\/([A-Za-z$][A-Za-z0-9$]*)\.html/g)].map((match) => match[1]!));
if (listed.size < 5000) throw new Error(`only ${listed.size} names -- did the listing change?`);

const PARALLEL = 6;
const unlisted = SYSTEM_NAMES.filter((name) => !listed.has(name));
const answered = new Set<string>();
const next = [...unlisted];
const worker = async () => {
  for (let name = next.pop(); name !== undefined; name = next.pop()) {
    const page = `https://reference.wolfram.com/language/ref/${encodeURIComponent(name)}.html`;
    for (let attempt = 0; ; attempt++) {
      const status = await fetch(page, { method: "HEAD", signal: AbortSignal.timeout(30_000) }).then(
        (reply) => reply.status,
        () => 0,
      );
      if (status === 200) answered.add(name);
      // Only a 404 says there is no page; anything else is retried, then fails the run.
      if (status === 200 || status === 404) break;
      if (attempt >= 3) throw new Error(`${page}: ${status}`);
      await new Promise((resolve) => setTimeout(resolve, 2000 * (attempt + 1)));
    }
  }
};
await Promise.all(Array.from({ length: PARALLEL }, worker));

const names = [...listed, ...answered].toSorted();

const source = `// GENERATED by reference/scripts/fetch-wolfram-documented.ts — do not edit by hand.
//
// Every symbol the Wolfram Language reference documents, from its alphabetical listing.
// Not every \`System\`\` symbol has a page; this is what says which do.

/** ${names.length} symbols. */
export const DOCUMENTED_NAMES: readonly string[] = ${JSON.stringify(names, null, 2)};

/** Whether the Wolfram Language reference has a page for \`name\`. */
export const isDocumentedName = (name: string): boolean => DOCUMENTED_NAME_SET.has(name);

const DOCUMENTED_NAME_SET = new Set(DOCUMENTED_NAMES);
`;

writeFileSync(new URL("../src/wolfram-documented-data.ts", import.meta.url), source);
process.stdout.write(`wolfram-documented-data.ts — ${names.length} symbols\n`);
